// scripts/build.mjs
// Zero-dependency bundler: concatenates the ES modules in dependency order into a single
// classic (non-module) script wrapped in an IIFE. A classic script loads fine when index.html
// is opened directly via file:// (double-click), where browsers block ES module imports (CORS).
//
// Usage: node scripts/build.mjs        -> writes dist/tetris.bundle.js
// The source modules in /src stay the single source of truth (unit tests import them directly).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Topological order: every module appears after all modules it imports.
export const MODULE_ORDER = Object.freeze([
  'src/randomizer.js',
  'src/pieces.js',
  'src/board.js',
  'src/scoring.js',
  'src/game.js',
  'src/effects.js',
  'src/renderer.js',
  'src/input/keyboard.js',
  'src/input/gamepad.js',
  'src/input/touch.js',
  'src/settings.js',
  'src/storage.js',
  'src/audio.js',
  'src/ui.js',
  'src/main.js',
]);

const IMPORT_RE = /^import\s[\s\S]*?\sfrom\s+['"][^'"]+['"];?[ \t]*\r?\n?/gm;
const EXPORT_DECL_RE = /^export\s+(?=(const|let|function|class|async\s+function)\s)/gm;
const UNSUPPORTED_EXPORT_RE = /^export\s+(default|\{|\*)/m;

/**
 * Strips import statements and `export` keywords from a module's source.
 * Throws if the module uses an export form this simple bundler cannot flatten.
 */
export function flattenModule(source, relPath) {
  if (UNSUPPORTED_EXPORT_RE.test(source)) {
    throw new Error(`Unsupported export form in ${relPath} (use "export const|function|class")`);
  }
  return source.replace(IMPORT_RE, '').replace(EXPORT_DECL_RE, '');
}

export function buildBundle() {
  const parts = MODULE_ORDER.map((relPath) => {
    const source = fs.readFileSync(path.join(ROOT, relPath), 'utf8');
    return `// ===== ${relPath} =====\n${flattenModule(source, relPath)}`;
  });
  return [
    '/* Prizma Tetris - generated by scripts/build.mjs. DO NOT EDIT; edit /src and rebuild. */',
    '(function () {',
    "'use strict';",
    ...parts,
    '})();',
    '',
  ].join('\n');
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const outDir = path.join(ROOT, 'dist');
  fs.mkdirSync(outDir, { recursive: true });
  const outFile = path.join(outDir, 'tetris.bundle.js');
  fs.writeFileSync(outFile, buildBundle());
  console.log(`Bundle written: ${path.relative(ROOT, outFile)}`);
}
