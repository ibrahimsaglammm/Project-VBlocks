import { DEFAULT_KEY_BINDINGS } from './input/keyboard.js';

export const DEFAULT_SETTINGS = Object.freeze({
  language: 'tr', // 'tr' | 'en'
  theme: 'neon', // 'neon' | 'classic' | 'minimal'
  colorblind: false,
  randomLevelColors: true, // Changes piece colors randomly on every new level
  ghost: true,
  grid: true,
  das: 167,
  arr: 33,
  sdf: 20,
  touchScheme: 'both', // 'gestures' | 'buttons' | 'both'
  touchSensitivity: 1.0,
  buttonSize: 'medium', // 'small' | 'medium' | 'large'
  leftHanded: false,
  haptics: true,
  musicVolume: 0.45,
  sfxVolume: 0.75,
  screenShake: true,
  particles: true,
  reducedMotion: false,
  allow180: true,
  infinityLock: false,
  keyBindings: { ...DEFAULT_KEY_BINDINGS },
});

export function sanitizeSettings(raw = {}) {
  return {
    ...DEFAULT_SETTINGS,
    ...raw,
    das: Math.max(50, Math.min(350, Number(raw.das ?? DEFAULT_SETTINGS.das))),
    arr: Math.max(0, Math.min(100, Number(raw.arr ?? DEFAULT_SETTINGS.arr))),
    sdf: Math.max(5, Math.min(40, Number(raw.sdf ?? DEFAULT_SETTINGS.sdf))),
    touchSensitivity: Math.max(
      0.5,
      Math.min(1.8, Number(raw.touchSensitivity ?? DEFAULT_SETTINGS.touchSensitivity))
    ),
    musicVolume: Math.max(0, Math.min(1, Number(raw.musicVolume ?? DEFAULT_SETTINGS.musicVolume))),
    sfxVolume: Math.max(0, Math.min(1, Number(raw.sfxVolume ?? DEFAULT_SETTINGS.sfxVolume))),
    keyBindings: {
      ...DEFAULT_KEY_BINDINGS,
      ...(raw.keyBindings || {}),
    },
  };
}

